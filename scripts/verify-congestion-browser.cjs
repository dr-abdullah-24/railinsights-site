const {chromium}=require(process.env.PLAYWRIGHT_PACKAGE);
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
let socket;
await page.routeWebSocket('ws://localhost:3001',ws=>{socket=ws;});
await page.goto('http://127.0.0.1:8081/congestion.html?feed=mock',{waitUntil:'networkidle'});
const now=Date.now();
const t=(extra={})=>({lat:51.53,lon:-.13,ts:now,delayTs:now,delayStatus:'LATE',delay:10,type:'passenger',td:'X0',berth:'1234',name:'Test junction',uid:'TEST',...extra});
socket.send(JSON.stringify({type:'state',trains:{'1A01':t({delay:22}),'1A02':t({lat:51.535}),'4A03':t({lon:-.14,type:'freight'}),'2B01':t({lat:53,delay:5})}}));
await page.locator('.cluster').waitFor();
assert.equal(await page.locator('#delayed').textContent(),'4');
await page.locator('.cluster').click();
assert.equal(await page.locator('#services tr').count(),3);
await page.locator('#clearSelection').click();
assert.equal(await page.locator('#services tr').count(),4);
await page.locator('#type').selectOption('freight');
assert.equal(await page.locator('#delayed').textContent(),'1');
await page.locator('#type').selectOption('all');
await page.locator('#threshold').selectOption('15');
assert.equal(await page.locator('#delayed').textContent(),'1');
await page.locator('#threshold').selectOption('3');
const downloadPromise=page.waitForEvent('download');await page.locator('#export').click();const download=await downloadPromise;assert.ok(download.suggestedFilename().endsWith('.csv'));
await page.screenshot({path:'congestion-desktop-check.jpg',quality:35,fullPage:false});
await page.locator('#basemap').selectOption('street');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'congestion-mobile-check.jpg',quality:35,fullPage:false});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
socket.send(JSON.stringify({type:'state',trains:{'1A01':t({delayTs:undefined})}}));
await page.waitForFunction(()=>document.getElementById('coverage').textContent==='0%');
assert.ok((await page.locator('#ranking').textContent()).includes('timestamps unavailable'));
socket.send(JSON.stringify({type:'state',trains:{}}));
await page.waitForFunction(()=>document.getElementById('positions').textContent==='0');
assert.equal(errors.length,0,errors.join('\n'));
console.log('Browser checks passed: cluster drill-down, filters, CSV, basemap switch, mobile overflow, missing timestamps, empty state; no page errors.');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
